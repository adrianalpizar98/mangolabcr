document.addEventListener('DOMContentLoaded', () => {
    // Manejo del idioma
    const langSwitchBtn = document.getElementById('lang-switch');
    const langTextEl = document.getElementById('lang-text');
    let currentLang = 'es';

    function setLanguage(lang) {
        currentLang = lang;
        langTextEl.textContent = lang === 'es' ? 'ENG' : 'ES';
        
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (translations[lang][key]) {
                el.textContent = translations[lang][key];
            }
        });
    }

    if (langSwitchBtn) {
        langSwitchBtn.addEventListener('click', () => {
            setLanguage(currentLang === 'es' ? 'en' : 'es');
        });
    }

    // Calculadora interactiva
    const methodSelect = document.getElementById('calc-method');
    const qtyInput = document.getElementById('calc-qty');
    const unitPriceEl = document.getElementById('calc-unit-price');
    const totalPriceEl = document.getElementById('calc-total-price');
    const whatsappBtn = document.getElementById('whatsapp-quote-btn');

    if (!methodSelect || !qtyInput) return;

    function calculatePrice() {
        const method = methodSelect.value;
        const qty = parseInt(qtyInput.value) || 0;
        let unitPrice = 0;

        if (method === 'serigrafia') {
            if (qty <= 100) {
                unitPrice = 5500;
            } else if (qty <= 300) {
                unitPrice = 5000;
            } else {
                unitPrice = 4500;
            }
        } else {
            if (qty <= 5) {
                unitPrice = 10000;
            } else if (qty <= 10) {
                unitPrice = 8000;
            } else if (qty <= 30) {
                unitPrice = 7000;
            } else {
                unitPrice = 6000;
            }
        }

        const total = qty * unitPrice;
        
        unitPriceEl.textContent = '\u20A1' + unitPrice.toLocaleString('es-CR');
        totalPriceEl.textContent = '\u20A1' + total.toLocaleString('es-CR');

        const msgText = currentLang === 'es' 
            ? `Hola Mango Lab! Quisiera cotizar ${qty} unidades por ${method.toUpperCase()}. Precio estimado: ?${total.toLocaleString('es-CR')}.`
            : `Hello Mango Lab! I would like to quote ${qty} units via ${method.toUpperCase()}. Estimated price: ?${total.toLocaleString('es-CR')}.`;

        const message = encodeURIComponent(msgText);
        whatsappBtn.href = `https://wa.me/50688760064?text=${message}`;
    }

    methodSelect.addEventListener('change', calculatePrice);
    qtyInput.addEventListener('input', calculatePrice);
    calculatePrice();
});
